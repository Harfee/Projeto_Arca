function renderizar_mais_animais(id_atual) {
    const grid = document.getElementById("mais_animais_grid");
    if (!grid) return;

    const outros = animais_data
        .filter(a => a.id !== id_atual)
        .sort(() => Math.random() - 0.5)
        .slice(0, 4);

    grid.innerHTML = "";

    outros.forEach(animal => {
        const card = document.createElement("div");
        card.className = "mini_card";
        card.onclick = () => ir_para_detalhe(animal.id);
        card.title = `Ver ${animal.nome}`;

        card.innerHTML = `
            <img
                class="mini_card_img"
                src="${getPrefix()}${animal.foto}"
                alt="${animal.nome}"
                onerror="this.style.display='none'; this.nextElementSibling.style.display='flex';"
            >
            <div class="mini_card_img_placeholder" style="display:none;">
                <i class="fa-solid fa-paw"></i>
            </div>
            <div class="mini_card_corpo">
                <div class="mini_card_nome">${animal.nome}</div>
                <div class="mini_card_info">${animal.idade_texto} · ${animal.sexo}</div>
                <div class="mini_card_raca">${animal.raca}</div>
            </div>
        `;

        grid.appendChild(card);
    });
}

function ir_para_detalhe(id) {
    window.location.href = `${getPrefix()}html/navbar/servicos/adocao/animal_detalhe.html?id=${id}`;
}


// ─── Termo de Comprometimento ─────────────────────────────────────────────────

function abrir_termo() {
    document.getElementById("checkbox_termo").checked = false;
    document.getElementById("btn_continuar").disabled = true;
    document.getElementById("modal_termo").classList.add("ativo");
    document.body.style.overflow = "hidden";
}

function fechar_termo() {
    document.getElementById("modal_termo").classList.remove("ativo");
    document.body.style.overflow = "";
}

function atualizar_btn_continuar() {
    const marcado = document.getElementById("checkbox_termo").checked;
    document.getElementById("btn_continuar").disabled = !marcado;
}


// ─── Confirmação de adoção ────────────────────────────────────────────────────

function confirmar_adocao() {
    fechar_termo();
    if (!animal_atual) return;
    window.location.href = `${getPrefix()}html/navbar/servicos/adocao/formulario_adocao.html?id=${animal_atual.id}`;
}

function fechar_confirmacao() {
    document.getElementById("confirmacao_overlay").classList.remove("ativo");
    document.body.style.overflow = "";
    window.location.href = `${getPrefix()}html/navbar/servicos/adocao/adocao.html`;
}