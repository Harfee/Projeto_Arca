let animal_atual = null;

// ─── Prefixo relativo até a raiz do projeto ───────────────────────────────────
function getPrefix() {
    const match = window.location.pathname.match(/\/Projeto_Arca\/(.*)/);
    if (!match || !match[1]) return './';
    const parts = match[1].split('/').filter(Boolean);
    const depth = parts.length - 1;
    if (depth <= 0) return './';
    return '../'.repeat(depth);
}

document.addEventListener("DOMContentLoaded", function () {
    const params = new URLSearchParams(window.location.search);
    const id = parseInt(params.get("id"));

    animal_atual = animais_data.find(a => a.id === id);

    if (!animal_atual) {
        document.getElementById("detalhe_wrapper").innerHTML = `
            <div style="text-align:center; padding:80px 20px; color:#64748b;">
                <i class="fa-solid fa-paw" style="font-size:52px; color:#cbd5e1; display:block; margin-bottom:16px;"></i>
                <p style="font-size:16px;">Animal não encontrado.</p>
                <a href="${getPrefix()}html/navbar/servicos/adocao/adocao.html" style="color:var(--cor-primaria); font-weight:600; text-decoration:none;">← Voltar para adoção</a>
            </div>
        `;
        return;
    }

    renderizar_detalhe(animal_atual);
    renderizar_mais_animais(animal_atual.id);

    document.getElementById("modal_termo").addEventListener("click", function (e) {
        if (e.target === this) fechar_termo();
    });

    document.getElementById("confirmacao_overlay").addEventListener("click", function (e) {
        if (e.target === this) fechar_confirmacao();
    });
});

