let visualizacao_atual = 'grid';

// ─── Prefixo relativo até a raiz do projeto ───────────────────────────────────
function getPrefix() {
    const match = window.location.pathname.match(/\/Projeto_Arca\/(.*)/);
    if (!match || !match[1]) return './';
    const parts = match[1].split('/').filter(Boolean);
    const depth = parts.length - 1;
    if (depth <= 0) return './';
    return '../'.repeat(depth);
}

document.addEventListener("DOMContentLoaded", function () {
    popular_racas();
    aplicar_filtros();
});

function popular_racas() {
    const select_raca = document.getElementById("filtro_raca");
    if (!select_raca) return;

    const racas = [...new Set(animais_data.map(a => a.raca))].sort();

    racas.forEach(raca => {
        const opt = document.createElement("option");
        opt.value = raca;
        opt.textContent = raca;
        select_raca.appendChild(opt);
    });
}

function aplicar_filtros() {
    const filtro_animal = document.getElementById("filtro_animal")?.value || "";
    const filtro_raca   = document.getElementById("filtro_raca")?.value   || "";
    const filtro_sexo   = document.getElementById("filtro_sexo")?.value   || "";
    const filtro_idade  = document.getElementById("filtro_idade")?.value  || "";
    const filtro_ordem  = document.getElementById("filtro_ordem")?.value  || "recente";
    const pesquisa      = (document.getElementById("input_pesquisa")?.value || "").toLowerCase().trim();

    let resultado = animais_data.filter(animal => {
        if (filtro_animal && animal.tipo !== filtro_animal) return false;
        if (filtro_raca   && animal.raca !== filtro_raca)   return false;
        if (filtro_sexo   && animal.sexo !== filtro_sexo)   return false;
        if (filtro_idade  && animal.idade_categoria !== filtro_idade) return false;
        if (pesquisa) {
            const haystack = `${animal.nome} ${animal.raca} ${animal.tipo} ${animal.sexo} ${animal.ong}`.toLowerCase();
            if (!haystack.includes(pesquisa)) return false;
        }
        return true;
    });

    if (filtro_ordem === "recente") {
        resultado.sort((a, b) => new Date(b.data_cadastro) - new Date(a.data_cadastro));
    } else if (filtro_ordem === "antigo") {
        resultado.sort((a, b) => new Date(a.data_cadastro) - new Date(b.data_cadastro));
    } else if (filtro_ordem === "az") {
        resultado.sort((a, b) => a.nome.localeCompare(b.nome, 'pt-BR'));
    }

    renderizar_cards(resultado);
}

function renderizar_cards(animais) {
    const container    = document.getElementById("adocao_cards");
    const sem_result   = document.getElementById("sem_resultados");
    const contador     = document.getElementById("contador_texto");

    if (!container) return;

    container.innerHTML = "";

    const total = animais.length;
    contador.textContent = `Exibindo ${total} resultado${total !== 1 ? 's' : ''}`;

    if (total === 0) {
        sem_result.style.display = "block";
        return;
    }

    sem_result.style.display = "none";

    animais.forEach(animal => {
        const card = criar_card(animal);
        container.appendChild(card);
    });
}

function criar_card(animal) {
    const card = document.createElement("div");
    card.className = "animal_card";

    const img_html = `
        <img
            class="animal_card_img"
            src="${getPrefix()}${animal.foto}"
            alt="Foto de ${animal.nome}"
            onerror="this.style.display='none'; this.nextElementSibling.style.display='flex';"
        >
        <div class="animal_card_img_placeholder" style="display:none;">
            <i class="fa-solid fa-paw"></i>
        </div>
    `;

    card.innerHTML = `
        ${img_html}
        <div class="animal_card_corpo">
            <div class="animal_card_nome">${animal.nome}</div>
            <div class="animal_card_info_linha">
                <span class="animal_card_idade">${animal.idade_texto}</span>
                <span class="animal_card_sexo">${animal.sexo}</span>
            </div>
            <div class="animal_card_raca">${animal.raca}</div>
            <p class="animal_card_descricao">${animal.descricao_curta}</p>
            <button class="btn_saiba_mais" onclick="ir_para_detalhe(${animal.id})">
                <i class="fa-solid fa-circle-plus"></i> Saiba mais
            </button>
        </div>
    `;

    return card;
}

function ir_para_detalhe(id) {
    window.location.href = `${getPrefix()}html/navbar/servicos/adocao/animal_detalhe.html?id=${id}`;
}

function mudar_visualizacao(tipo) {
    visualizacao_atual = tipo;

    const container  = document.getElementById("adocao_cards");
    const btn_lista  = document.getElementById("btn_lista");
    const btn_grid   = document.getElementById("btn_grid");

    if (!container) return;

    container.classList.remove("grid", "lista");
    container.classList.add(tipo);

    btn_lista.classList.toggle("active", tipo === "lista");
    btn_grid.classList.toggle("active",  tipo === "grid");
}