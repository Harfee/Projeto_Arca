function enviar_solicitacao() {
    if (!validar_etapa_2()) return;

    const a = animal_atual;

    document.getElementById("confirmacao_nome_animal").textContent = a.nome;
    const partes = [a.tipo, a.sexo, a.idade_texto, a.raca].filter(Boolean);
    document.getElementById("confirmacao_detalhe_animal").textContent = partes.join(" · ");

    const placeholder = document.getElementById("confirmacao_foto_placeholder");
    const img         = document.getElementById("confirmacao_foto_img");
    img.src           = a.foto;
    img.alt           = a.nome;
    img.style.display = "block";
    placeholder.style.display = "none";
    img.onerror = () => {
        img.style.display = "none";
        placeholder.style.display = "flex";
    };

    const insta = a.contato_instagram || "—";
    document.getElementById("confirmacao_instagram").textContent = insta;
    if (a.contato_instagram) {
        document.getElementById("confirmacao_instagram").href =
            `https://instagram.com/${a.contato_instagram.replace("@", "")}`;
    } else {
        document.getElementById("confirmacao_instagram").removeAttribute("href");
    }

    document.getElementById("confirmacao_tel").textContent = a.contato_tel || "—";
    document.getElementById("confirmacao_ong").textContent = a.ong || "—";

    document.getElementById("confirmacao_overlay").classList.add("ativo");
    document.body.style.overflow = "hidden";
}

function fechar_confirmacao() {
    document.getElementById("confirmacao_overlay").classList.remove("ativo");
    document.body.style.overflow = "";
    window.location.href = "/html/navbar/servicos/adocao/adocao.html";
}