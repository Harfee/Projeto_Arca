let animal_atual = null;

document.addEventListener("DOMContentLoaded", function () {
    const params = new URLSearchParams(window.location.search);
    const id = parseInt(params.get("id"));
    animal_atual = animais_data.find(a => a.id === id) || animais_data[0];

    renderizar_animal(animal_atual);
    popular_datas("data_dd", "data_mm", "data_yyyy");
    carregar_bairros();
    iniciar_upload();

    document.getElementById("cpf").addEventListener("input", function (e) {
        let v = e.target.value.replace(/\D/g, "").slice(0, 11);
        v = v.replace(/(\d{3})(\d)/, "$1.$2");
        v = v.replace(/(\d{3})(\d)/, "$1.$2");
        v = v.replace(/(\d{3})(\d{1,2})$/, "$1-$2");
        e.target.value = v;
    });

    document.getElementById("telefone").addEventListener("input", function (e) {
        let v = e.target.value.replace(/\D/g, "").slice(0, 11);
        if (v.length > 6) v = v.replace(/(\d{2})(\d{5})(\d{0,4}).*/, "($1) $2-$3");
        else if (v.length > 2) v = v.replace(/(\d{2})(\d{0,5})/, "($1) $2");
        e.target.value = v;
    });

    document.getElementById("cep").addEventListener("input", function (e) {
        let v = e.target.value.replace(/\D/g, "").slice(0, 8);
        if (v.length > 5) v = v.replace(/(\d{5})(\d{0,3})/, "$1-$2");
        e.target.value = v;
    });

    ["moradia", "quintal", "aluguel", "pets"].forEach(grupo => {
        document.querySelectorAll(`input[name="${grupo}"]`).forEach(cb => {
            cb.addEventListener("change", function () {
                if (this.checked) {
                    document.querySelectorAll(`input[name="${grupo}"]`).forEach(o => {
                        if (o !== this) o.checked = false;
                    });
                }
            });
        });
    });

    document.getElementById("confirmacao_overlay").addEventListener("click", function (e) {
        if (e.target === this) fechar_confirmacao();
    });
});

function iniciar_upload() {
    const dropzone = document.getElementById("upload_dropzone");
    const input    = document.getElementById("comprovante");

    if (!dropzone || !input) return;

    dropzone.addEventListener("click", function (e) {
        if (e.target.closest(".upload_btn_browse") || e.target.closest(".upload_btn_remover")) return;
        input.click();
    });

    dropzone.addEventListener("dragover", function (e) {
        e.preventDefault();
        dropzone.classList.add("dragover");
    });

    dropzone.addEventListener("dragleave", function () {
        dropzone.classList.remove("dragover");
    });

    dropzone.addEventListener("drop", function (e) {
        e.preventDefault();
        dropzone.classList.remove("dragover");
        const arquivo = e.dataTransfer.files[0];
        if (arquivo) aplicar_arquivo(arquivo);
    });

    input.addEventListener("change", function () {
        if (input.files[0]) aplicar_arquivo(input.files[0]);
    });
}

function aplicar_arquivo(arquivo) {
    document.getElementById("upload_nome").textContent = arquivo.name;
    document.getElementById("upload_dropzone_conteudo").style.display = "none";
    document.getElementById("upload_arquivo_selecionado").style.display = "flex";
}

function remover_arquivo() {
    document.getElementById("comprovante").value = "";
    document.getElementById("upload_nome").textContent = "—";
    document.getElementById("upload_dropzone_conteudo").style.display = "flex";
    document.getElementById("upload_arquivo_selecionado").style.display = "none";
}

function popular_datas(id_dia, id_mes, id_ano) {
    const select_dia = document.getElementById(id_dia);
    const select_mes = document.getElementById(id_mes);
    const select_ano = document.getElementById(id_ano);
    if (!select_dia || !select_mes || !select_ano) return;

    for (let d = 1; d <= 31; d++) {
        const opt = document.createElement("option");
        opt.value = d < 10 ? "0" + d : d;
        opt.textContent = d < 10 ? "0" + d : d;
        select_dia.appendChild(opt);
    }
    for (let m = 1; m <= 12; m++) {
        const opt = document.createElement("option");
        opt.value = m < 10 ? "0" + m : m;
        opt.textContent = m < 10 ? "0" + m : m;
        select_mes.appendChild(opt);
    }
    const ano_atual = new Date().getFullYear();
    for (let a = ano_atual; a >= ano_atual - 100; a--) {
        const opt = document.createElement("option");
        opt.value = a;
        opt.textContent = a;
        select_ano.appendChild(opt);
    }
}

function carregar_bairros() {
    const select_bairro = document.getElementById("bairro");
    if (!select_bairro) return;
    bairros_serra.forEach(bairro => {
        const option = document.createElement("option");
        option.value = bairro;
        option.textContent = bairro;
        select_bairro.appendChild(option);
    });
}

function renderizar_animal(a) {
    document.getElementById("animal_nome").textContent  = a.nome;
    document.getElementById("animal_porte").textContent = a.porte;
    document.getElementById("animal_idade").textContent = a.idade_texto;
    document.getElementById("animal_tipo").textContent  = a.tipo;
    document.getElementById("animal_ong").textContent   = a.ong;

    const wrap = document.getElementById("animal_foto_wrapper");
    const img  = document.createElement("img");
    img.src = a.foto;
    img.alt = a.nome;
    img.onerror = () => { wrap.innerHTML = '<i class="fa-solid fa-paw placeholder_paw"></i>'; };
    wrap.innerHTML = "";
    wrap.appendChild(img);
}

